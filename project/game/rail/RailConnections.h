// =====================================================================
//  RailConnections：レール間の接続情報をロード時に1回だけ計算する。
//   ・ループ：始点と終点が近いレールは閉じたレール（円状）
//   ・連結：端点(front/back)同士が近いレールを「連結」とみなし、最も近い端点を選ぶ（交差点で誤接続しない）。
//     連結端点は中点へ"溶接"してノードを一致させる → 隙間があっても乗り継ぎでワープしない
//   ・途中分岐：あるレールの端が別のレールの途中に接している T字路（同タイプ同士でも乗り換えられる）
//   ※動くレール(HasMotion)は静的連結しない（位置が変わるため。プレイヤーの動的ドッキングに任せる）。
//   ※レールのタイプ（横/縦）と動きの設定を先に割り当ててから呼ぶこと（分岐キーの向きと除外判定に使う）
// =====================================================================
